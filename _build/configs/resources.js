/**
 * Страницы пакета.
 *
 * Поддерживаются ДВА формата.
 *
 * 1) Плоский — как раньше. Ключ верхнего уровня = контекст:
 *
 *    export default {
 *        'web': {
 *            'catalog': { 'pagetitle': 'Каталог', ... },
 *        }
 *    }
 *
 *    Родитель по умолчанию — корень. Его можно не зашивать числом:
 *      'parent_setting'   — системная настройка с id родителя (приоритет)
 *      'parent_alias'     — искать родителя по алиасу
 *      'template_setting' — системная настройка с ИМЕНЕМ шаблона
 *
 * 2) По сайтам — когда на разных сайтах разные родители и шаблоны. Ключ верхнего
 *    уровня = список идентификаторов сайта через запятую, значение = обычная
 *    структура из п.1. Внутри блока родителя и шаблон можно писать прямо
 *    числом/именем: блок уже привязан к конкретному сайту.
 *
 *    Сайт опознаётся тремя способами:
 *      - МЕТКА САЙТА — значение системной настройки `gtsapi_site_key` ('prod', 'office'…),
 *        задаётся один раз на инсталляции. Единственный способ, не раскрывающий адреса,
 *        поэтому в публично распространяемых пакетах используйте его;
 *      - хост — 'site.ru' (регистр, порт и www. не важны);
 *      - хеш хоста — 'sha1:9f7ec52deaa0' (можно префикс), если метку заводить не хочется.
 *
 *    export default {
 *        'prod': {
 *            'web': {
 *                'journal': {
 *                    'pagetitle': 'Журнал',
 *                    'parent': 248,
 *                    'properties': { 'templatename': 'adminTemplate' },
 *                    'groups': 'administrator',   // site-specific имена здесь допустимы
 *                },
 *            },
 *        },
 *        'office,dev': { 'web': { 'journal': { 'pagetitle': 'Журнал', 'parent': 197 } } },
 *        '*':          { 'web': { 'journal': { 'pagetitle': 'Журнал' } } },   // в корень
 *    }
 *
 *    Нет совпадения и нет '*' — страницы не создаются, а в лог пишется предупреждение
 *    с текущей меткой и хешем хоста, чтобы было понятно, какой ключ прописать.
 *
 * Общее для обоих форматов:
 *   'config_name' — системная настройка, в которую пишется id созданной страницы;
 *                   ссылаться в коде нужно на неё, а не на номер;
 *   'update': false — существующую страницу при обновлении пакета не перетирать;
 *   'resources': { ... } — вложенные дочерние страницы;
 *   контент берётся из core/components/<pkg>/elements/resources/<context>/<uri>.tpl
 *
 * Защита: если алиас на сайте занят ЧУЖОЙ страницей, резолвер её не трогает и создаёт
 * свою с префиксом пакета — иначе обновление затёрло бы чужой заголовок и контент.
 *
 * ⚠️ Для публично распространяемого пакета файл имеет смысл оставить пустым: чужому
 * сайту пакет, самовольно создающий страницы, обычно не нужен. Пользователь создаст
 * ресурс сам и вставит вызов mixVue.
 */
